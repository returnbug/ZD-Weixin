async function 其他下拉(参数 = {}) {
	const 请求会话 = 确保当前缓存会话()
	const 请求缓存键 = 创建请求缓存键(参数)
	const 缓存键 = `${首页下拉缓存前缀}${请求缓存键}`
	const 内存缓存 = 首页下拉数据缓存[请求缓存键]

	if (内存缓存 && Date.now() - 内存缓存.time <= 首页下拉缓存有效时间) {
		return 内存缓存.data
	}

	if (内存缓存) {
		delete 首页下拉数据缓存[请求缓存键]
	}

	const 本地缓存 = 读取缓存(缓存键, 首页下拉缓存有效时间)

	if (本地缓存) {
		return 本地缓存
	}

	if (首页下拉请求缓存[请求缓存键]) {
		return 首页下拉请求缓存[请求缓存键]
	}

	// 下拉数据属于静态配置；缓存结果和进行中的 Promise，避免页面返回或并发初始化时重复请求。
	const 下拉请求 = 新能源请求('其他下拉', 参数).then((响应数据) => {
		const 下拉数据 = 标准化首页下拉(响应数据)

		if (请求会话 === 当前缓存会话标识 && 请求会话 === 读取当前缓存会话标识()) {
			首页下拉数据缓存[请求缓存键] = {
				data: 下拉数据,
				time: Date.now()
			}
			写入缓存(缓存键, 下拉数据)
		}

		return 下拉数据
	}).finally(() => {
		if (首页下拉请求缓存[请求缓存键] === 下拉请求) {
			delete 首页下拉请求缓存[请求缓存键]
		}
	})

	首页下拉请求缓存[请求缓存键] = 下拉请求

	return 下拉请求
}

async function 获取首页区域类型() {
	const 下拉 = await 其他下拉()

	return 下拉.区域类型
}

