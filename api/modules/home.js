function 对象字典转模块列表(数据) {
	if (!数据 || typeof 数据 !== 'object' || Array.isArray(数据)) {
		return []
	}

	// public 的 normalizeApps 会把 { [id]: app } 转成数组，并用对象键兜底 ID。
	return Object.entries(数据).map(([id, 模块]) => {
		if (模块 && typeof 模块 === 'object' && !Array.isArray(模块)) {
			const 模块ID = 模块.ID !== undefined && 模块.ID !== null && 模块.ID !== '' ? 模块.ID : id

			return {
				...模块,
				ID: 模块ID
			}
		}

		return {
			ID: id,
			名称: 转为文本(模块)
		}
	})
}

