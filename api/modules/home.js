function 格式化大屏数值(值) {
	if (值 === undefined || 值 === null || 值 === '') {
		return ''
	}

	const 数字 = Number.parseFloat(值)

	return Number.isFinite(数字) ? String(数字) : 转为文本(值)
}

function 格式化大屏带单位数值(值, 单位 = '') {
	const 文本 = 格式化大屏数值(值)

	return 文本 ? `${文本}${单位}` : ''
}

function 读取大屏数值(对象, 字段列表, 默认值 = 0) {
	const 数字 = Number.parseFloat(读取首个有效字段(对象, 字段列表))

	return Number.isFinite(数字) ? 数字 : 默认值
}

function 创建首页状态数据(大屏数据, 当前状态数据) {
	const 通讯数据 = 读取首个有效字段(大屏数据, 通讯统计字段, {})
	const 通讯 = 是否普通对象(通讯数据) ? 通讯数据 : {}
	const 无报警 = 读取大屏数值(通讯, ['无报警'])
	const 有报警 = 读取大屏数值(通讯, ['有报警'])
	const 状态列表 = Array.isArray(当前状态数据) ? 当前状态数据 : 默认首页状态数据

	// 保持原首页逻辑：通讯统计缺少单项时按 0 展示，其余板块才沿用当前页面数据兜底。
	const 状态数值 = {
		电站总数: 无报警 + 有报警,
		接入中: 读取大屏数值(通讯, ['接入中']),
		部分离线: 读取大屏数值(通讯, ['部分离线']),
		全部离线: 读取大屏数值(通讯, ['全部离线']),
		通讯正常: 读取大屏数值(通讯, 通讯正常字段),
		有报警
	}

	return 状态列表.map((项) => ({
		...项,
		数值: 状态数值[项.标题] !== undefined ? String(状态数值[项.标题]) : 项.数值
	}))
}

