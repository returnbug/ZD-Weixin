function 判断模块是否可用(模块) {
	const 状态 = 读取对象字段(模块, ['状态', 'status', '启用状态'])

	if (状态 === undefined || 状态 === null || 状态 === '') {
		return true
	}

	if (typeof 状态 === 'boolean') {
		return 状态
	}

	return !['0', 'false', '禁用', '停用', '关闭', '未开通', '待开通', '不可用'].includes(String(状态))
}

function 创建请求缓存键(参数 = {}) {
	if (!是否普通对象(参数)) {
		return JSON.stringify(参数 || {})
	}

	// 扁平请求参数按键名排序，确保属性顺序不同但内容相同的请求可以共用 Promise。
	const 排序参数 = Object.keys(参数).sort().reduce((结果, 键) => {
		结果[键] = 参数[键]
		return 结果
	}, {})

	return JSON.stringify(排序参数)
}

