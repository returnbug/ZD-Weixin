import {
	转为文本,
	是否普通对象,
	解析下拉列表,
	创建参数缓存键,
	清空缓存对象,
	读取有效内存缓存,
	复用在途请求,
	读取当前缓存会话标识,
	标准化区域类型,
	读取默认区域类型,
	读取可见区域ID,
	新能源请求,
	解析下拉对象,
	解析字段列表,
	解析数据行列表
} from '../base.js'

const 报警文件名 = '报警日志'
const 报警字段区域类型 = '区域1'
const 默认显条 = 50
const 静态配置缓存有效时间 = 30 * 60 * 1000
const 报警详情缓存键 = '报警详情临时缓存'
const 旧报警详情缓存前缀 = '报警详情:'
const 报警下拉数据缓存 = Object.create(null)
const 报警下拉请求缓存 = Object.create(null)
const 报警字段缓存 = Object.create(null)
const 报警字段请求缓存 = Object.create(null)
const 报警数据请求缓存 = Object.create(null)
let 当前缓存会话标识 = null
let 已清理旧报警详情缓存 = false

function 确保当前缓存会话() {
	const 当前会话 = 读取当前缓存会话标识()

	if (当前缓存会话标识 === 当前会话) {
		return 当前会话
	}

	// 会话切换时丢弃旧结果和旧在途 Promise 的引用，新账号只能建立自己的业务缓存。
	[
		报警下拉数据缓存,
		报警下拉请求缓存,
		报警字段缓存,
		报警字段请求缓存,
		报警数据请求缓存
	].forEach(清空缓存对象)
	当前缓存会话标识 = 当前会话

	return 当前会话
}

function 读取有效字段缓存(缓存键) {
	return 读取有效内存缓存(报警字段缓存, 缓存键, 静态配置缓存有效时间)
}

function 解析报警下拉数据(响应数据) {
	const 下拉 = 解析下拉对象(响应数据)

	return {
		设备类型: [...new Set(['全部类型', ...解析下拉列表(下拉.设备类型)])],
		恢复状态: [...new Set(['全部状态', '未恢复', '已恢复', ...解析下拉列表(下拉.恢复状态)])],
		区域类型: 读取默认区域类型(下拉.区域类型)
	}
}

async function 其他下拉(参数 = {}) {
	const 请求会话 = 确保当前缓存会话()
	const 缓存键 = 创建参数缓存键(是否普通对象(参数) ? 参数 : {})
	const 下拉缓存 = 读取有效内存缓存(报警下拉数据缓存, 缓存键, 静态配置缓存有效时间)

	if (下拉缓存) {
		return 下拉缓存
	}

	return 复用在途请求(报警下拉请求缓存, 缓存键, async () => {
		const 响应数据 = await 新能源请求('其他下拉', 参数)
		const 下拉数据 = 解析报警下拉数据(响应数据)

		// 下拉属于静态筛选数据，仅在当前登录会话内缓存 30 分钟。
		if (请求会话 === 当前缓存会话标识 && 请求会话 === 读取当前缓存会话标识()) {
			报警下拉数据缓存[缓存键] = {
				data: 下拉数据,
				time: Date.now()
			}
		}
		return 下拉数据
	})
}

async function bj加载字段(参数 = {}) {
	const 请求会话 = 确保当前缓存会话()
	const 区域类型 = 标准化区域类型(参数.区域类型 || 报警字段区域类型)
	const 缓存键 = 区域类型
	const 字段缓存 = 读取有效字段缓存(缓存键)

	if (字段缓存) {
		return 字段缓存.响应数据
	}

	return 复用在途请求(报警字段请求缓存, 缓存键, async () => {
		const 响应数据 = await 新能源请求('bj加载字段', { 区域类型 })
		// 原响应和解析后的列顺序共用同一条缓存，同时失效。
		if (请求会话 === 当前缓存会话标识 && 请求会话 === 读取当前缓存会话标识()) {
			报警字段缓存[缓存键] = {
				data: { 响应数据, 字段列表: 解析字段列表(响应数据) },
				time: Date.now()
			}
		}
		return 响应数据
	})
}

function 创建报警数据参数(参数 = {}) {
	const 区域类型 = 标准化区域类型(参数.区域类型 || 报警字段区域类型)

	return {
		文件: 参数.文件 || 报警文件名,
		显条: 参数.显条 || 默认显条,
		当页: 参数.当页 || 1,
		模式: 参数.模式 || '查询',
		树选: 参数.树选 || '',
		条件: 参数.条件 || '',
		可见: 参数.可见 !== undefined ? 参数.可见 : 读取可见区域ID(区域类型),
		系统类型: 参数.系统类型 || '全部类型',
		设备类型: 参数.设备类型 || '全部类型',
		设备模版: 参数.设备模版 || '全部模版',
		报警类型: 参数.报警类型 || '全部类型',
		恢复状态: 参数.恢复状态 || '全部状态',
		区域类型,
	}
}

function 请求报警数据(请求参数 = {}) {
	确保当前缓存会话()
	const 缓存键 = 创建参数缓存键(请求参数)

	// 动态列表只缓存原始在途请求，既避免重复网络调用，也保持 bj加载数据 的原返回格式。
	return 复用在途请求(报警数据请求缓存, 缓存键, () => 新能源请求('bj加载数据', 请求参数))
}

async function bj加载数据(参数 = {}) {
	return 请求报警数据(创建报警数据参数(参数))
}

async function 获取报警列表(参数 = {}) {
	const 请求参数 = 创建报警数据参数(参数)
	const [字段列表, 响应数据] = await Promise.all([
		读取报警数据字段列表(请求参数),
		请求报警数据(请求参数)
	])
	const 数据字段列表 = 字段列表.length ? 字段列表 : 解析字段列表(响应数据)

	// 二维行解析、空值与字段别名统一在接口层完成，页面只消费标准报警对象。
	return 解析标准报警列表(响应数据, 数据字段列表, 请求参数)
}

function 解析报警行列表(响应数据, 字段列表 = []) {
	return 解析数据行列表(响应数据, 字段列表, '报警内容')
}

async function 读取报警数据字段列表(请求参数 = {}) {
	确保当前缓存会话()
	const 缓存键 = 标准化区域类型(请求参数.区域类型 || 报警字段区域类型)
	const 字段缓存 = 读取有效字段缓存(缓存键)

	if (字段缓存) {
		return 字段缓存.字段列表
	}

	try {
		const 字段响应 = await bj加载字段({
			区域类型: 缓存键
		})

		const 最新字段缓存 = 读取有效字段缓存(缓存键)
		return 最新字段缓存 ? 最新字段缓存.字段列表 : 解析字段列表(字段响应)
	} catch (错误) {
		return []
	}
}

function 标准化报警状态(值) {
	const 文本 = 转为文本(值)

	if (/未恢复|未处理|发生|报警中/.test(文本)) {
		return '发生中'
	}

	if (/已恢复|恢复|已处理|正常/.test(文本)) {
		return '已恢复'
	}

	return 文本 || '发生中'
}

function 是否有效恢复时间(值) {
	const 文本 = 转为文本(值)

	return Boolean(文本 && !['-', '--', '无', '未恢复', 'null', 'undefined'].includes(文本))
}

function 是否全部恢复状态(值) {
	return ['全部', '全部状态', '全部类型'].includes(转为文本(值))
}

function 读取报警状态(恢复状态, 恢复时间, 请求恢复状态 = '') {
	const 状态文本 = 转为文本(恢复状态)
	const 请求状态文本 = 转为文本(请求恢复状态)

	if (状态文本 && !是否全部恢复状态(状态文本)) {
		return 标准化报警状态(状态文本)
	}

	if (请求状态文本 && !是否全部恢复状态(请求状态文本)) {
		return 标准化报警状态(请求状态文本)
	}

	if (是否全部恢复状态(请求状态文本) && 是否有效恢复时间(恢复时间)) {
		return '已恢复'
	}

	return '发生中'
}

function 创建报警标题(行对象) {
	const 标题 = 转为文本(行对象.日志内容)

	if (标题) {
		return 标题
	}

	const 设备名称 = 转为文本(行对象.设备信息)
	const 状态 = 标准化报警状态(行对象.恢复状态)

	return [设备名称, 状态].filter(Boolean).join(' ') || '报警信息'
}

function 标准化报警信息(行对象 = {}, 索引 = 0, 请求恢复状态 = '') {
	// bj加载字段使用“模版名称”“设备信息”等固定列名，页面名称在这里一次性转换。
	const 数据 = 是否普通对象(行对象) ? 行对象 : {}
	const 发生时间 = 转为文本(数据.开始时间)
	const 设备名称 = 转为文本(数据.设备信息)
	const 模板名称 = 转为文本(数据.模版名称)
	const 数据名称 = 转为文本(数据.数据名称)
	const 报警编号 = 转为文本(数据.ID) ||
		`${发生时间 || '报警'}-${设备名称 || 索引}`
	// 当前后端不返回恢复状态列，继续按请求筛选和结束时间沿用原状态判定。
	const 恢复状态 = 数据.恢复状态
	const 恢复时间 = 转为文本(数据.结束时间)

	return {
		...行对象,
		id: 报警编号,
		标题: 创建报警标题(数据),
		状态: 读取报警状态(恢复状态, 恢复时间, 请求恢复状态),
		级别: 转为文本(数据.报警类型),
		设备类型: 转为文本(数据.设备类型),
		设备名称,
		模板名称,
		数据名称,
		电站名称: 转为文本(数据.所属电站),
		发生时间,
		发生日期: 发生时间 ? 发生时间.slice(0, 10) : '',
		恢复时间,
		说明: 转为文本(数据.日志内容)
	}
}

function 解析标准报警列表(响应数据, 字段列表 = [], 请求参数 = {}) {
	const 当前页 = Number(请求参数.当页) || 1
	const 每页显条 = Number(请求参数.显条) || 默认显条
	const 起始索引 = (当前页 - 1) * 每页显条

	return 解析报警行列表(响应数据, 字段列表).map((报警行, 索引) => {
		return 标准化报警信息(报警行, 起始索引 + 索引, 请求参数.恢复状态)
	})
}

function 写入报警详情缓存(报警信息 = {}) {
	if (!报警信息 || !报警信息.id) {
		return
	}

	清理旧报警详情缓存()
	// 报警详情只用于列表到详情页的临时传递，固定单键覆盖以免按 ID 永久累积。
	uni.setStorageSync(报警详情缓存键, {
		报警编号: 转为文本(报警信息.id),
		报警信息,
		session: 读取当前缓存会话标识()
	})
}

function 读取报警详情缓存(报警编号 = '') {
	if (!报警编号) {
		return {}
	}

	清理旧报警详情缓存()
	const 缓存数据 = uni.getStorageSync(报警详情缓存键)
	const 当前会话 = 读取当前缓存会话标识()

	if (!缓存数据 || typeof 缓存数据 !== 'object' || 缓存数据.session !== 当前会话) {
		if (缓存数据) {
			uni.removeStorageSync(报警详情缓存键)
		}
		return {}
	}

	return 缓存数据.报警编号 === 转为文本(报警编号) ? 缓存数据.报警信息 || {} : {}
}

function 清理旧报警详情缓存() {
	if (已清理旧报警详情缓存) {
		return
	}

	if (typeof uni.getStorageInfoSync !== 'function') {
		已清理旧报警详情缓存 = true
		return
	}

	try {
		const 存储信息 = uni.getStorageInfoSync() || {}
		const 缓存键列表 = Array.isArray(存储信息.keys) ? 存储信息.keys : []

		缓存键列表.forEach((缓存键) => {
			if (缓存键.startsWith(旧报警详情缓存前缀)) {
				uni.removeStorageSync(缓存键)
			}
		})
		已清理旧报警详情缓存 = true
	} catch (错误) {
		// 历史缓存迁移失败不能阻断当前报警详情跳转，后续读写时继续尝试清理。
	}
}

