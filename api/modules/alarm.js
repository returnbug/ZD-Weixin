function 清空缓存对象(缓存对象) {
	Object.keys(缓存对象).forEach((缓存键) => {
		delete 缓存对象[缓存键]
	})
}

function 确保当前缓存会话() {
	const 当前会话 = 读取当前缓存会话标识()

	if (当前缓存会话标识 === 当前会话) {
		return 当前会话
	}

	// 会话切换时丢弃旧结果和旧在途 Promise 的引用，新账号只能建立自己的业务缓存。
	[
		报警下拉数据缓存,
		报警下拉请求缓存,
		报警字段响应缓存,
		报警字段列表缓存,
		报警字段请求缓存,
		报警数据请求缓存
	].forEach(清空缓存对象)
	当前缓存会话标识 = 当前会话

	return 当前会话
}

function 读取有效字段缓存(缓存键) {
	const 响应缓存 = 报警字段响应缓存[缓存键]
	const 列表缓存 = 报警字段列表缓存[缓存键]
	const 当前时间 = Date.now()
	const 缓存有效 = 响应缓存 && 列表缓存 &&
		当前时间 - 响应缓存.time <= 静态配置缓存有效时间 &&
		当前时间 - 列表缓存.time <= 静态配置缓存有效时间

	if (缓存有效) {
		return {
			响应数据: 响应缓存.data,
			字段列表: 列表缓存.data
		}
	}

	// 字段原始响应与解析顺序成对失效，防止报警二维行使用过期列顺序。
	delete 报警字段响应缓存[缓存键]
	delete 报警字段列表缓存[缓存键]
	return null
}

function 创建参数缓存键(参数 = {}) {
	const 参数对象 = 参数 && typeof 参数 === 'object' && !Array.isArray(参数) ? 参数 : {}

	// 当前接口参数均为扁平对象，按键名排序后可让相同参数稳定命中同一个请求缓存。
	return JSON.stringify(Object.keys(参数对象).sort().reduce((结果, 键) => {
		结果[键] = 参数对象[键]
		return 结果
	}, {}))
}

