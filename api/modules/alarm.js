async function 其他下拉(参数 = {}) {
	const 请求会话 = 确保当前缓存会话()
	const 缓存键 = 创建参数缓存键(参数)
	const 下拉缓存 = 报警下拉数据缓存[缓存键]

	if (下拉缓存 && Date.now() - 下拉缓存.time <= 静态配置缓存有效时间) {
		return 下拉缓存.data
	}

	if (下拉缓存) {
		delete 报警下拉数据缓存[缓存键]
	}

	if (报警下拉请求缓存[缓存键]) {
		return 报警下拉请求缓存[缓存键]
	}

	const 下拉请求 = 新能源请求('其他下拉', 参数).then((响应数据) => {
		const 下拉数据 = 解析报警下拉数据(响应数据)

		// 下拉属于静态筛选数据，仅在当前登录会话内缓存 30 分钟。
		if (请求会话 === 当前缓存会话标识 && 请求会话 === 读取当前缓存会话标识()) {
			报警下拉数据缓存[缓存键] = {
				data: 下拉数据,
				time: Date.now()
			}
		}
		return 下拉数据
	}).finally(() => {
		if (报警下拉请求缓存[缓存键] === 下拉请求) {
			delete 报警下拉请求缓存[缓存键]
		}
	})

	报警下拉请求缓存[缓存键] = 下拉请求

	return 下拉请求
}

async function bj加载字段(参数 = {}) {
	const 请求会话 = 确保当前缓存会话()
	const 区域类型 = 标准化区域类型(参数.区域类型 || 报警字段区域类型)
	const 缓存键 = 区域类型
	const 字段缓存 = 读取有效字段缓存(缓存键)

	if (字段缓存) {
		return 字段缓存.响应数据
	}

	if (报警字段请求缓存[缓存键]) {
		return 报警字段请求缓存[缓存键]
	}

	const 字段请求 = 新能源请求('bj加载字段', {
		区域类型
	}).then((响应数据) => {
		// console.log('bj加载字段响应数据', 响应数据)
		// 同一区域的字段定义和顺序固定，同时缓存原响应与解析结果供列表映射复用。
		if (请求会话 === 当前缓存会话标识 && 请求会话 === 读取当前缓存会话标识()) {
			const 缓存时间 = Date.now()
			报警字段响应缓存[缓存键] = {
				data: 响应数据,
				time: 缓存时间
			}
			报警字段列表缓存[缓存键] = {
				data: 解析字段列表(响应数据),
				time: 缓存时间
			}
		}
		return 响应数据
	}).finally(() => {
		if (报警字段请求缓存[缓存键] === 字段请求) {
			delete 报警字段请求缓存[缓存键]
		}
	})

	报警字段请求缓存[缓存键] = 字段请求

	return 字段请求
}

