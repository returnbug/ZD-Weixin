import {
	新能源基础地址,
	转为文本,
	解析下拉列表,
	创建参数缓存键,
	清空缓存对象,
	读取有效内存缓存,
	复用在途请求,
	读取当前缓存会话标识,
	标准化区域类型,
	读取默认区域类型,
	读取可见区域ID,
	新能源请求,
	解析下拉对象,
	解析字段列表,
	解析数据行列表
} from '../base.js'

const 光伏文件名 = '光伏'
const 光伏系统类型 = '光伏'
const 光伏默认区域类型 = '区域1'
const 默认显条 = 50
const 静态配置缓存有效时间 = 30 * 60 * 1000
const 光伏字段缓存 = Object.create(null)
const 光伏字段请求缓存 = Object.create(null)
const 光伏下拉响应缓存 = Object.create(null)
const 光伏下拉请求缓存 = Object.create(null)
const 光伏数据请求缓存 = Object.create(null)
const 光伏详情请求缓存 = Object.create(null)
let 当前缓存会话标识 = null

function 确保当前缓存会话() {
	const 当前会话 = 读取当前缓存会话标识()

	if (当前缓存会话标识 === 当前会话) {
		return 当前会话
	}

	// 登录会话变化后清空本模块引用，避免新账号命中旧账号的静态结果或在途请求。
	[
		光伏字段缓存,
		光伏字段请求缓存,
		光伏下拉响应缓存,
		光伏下拉请求缓存,
		光伏数据请求缓存,
		光伏详情请求缓存
	].forEach(清空缓存对象)
	当前缓存会话标识 = 当前会话

	return 当前会话
}

function 创建电站图片地址(电站图片 = '') {
	const 图片名称 = 转为文本(电站图片).replace(/^\/+/, '')

	if (!图片名称) {
		return ''
	}

	const 基础地址 = 新能源基础地址.endsWith('/') ? 新能源基础地址 : `${新能源基础地址}/`

	// 电站图片是后端静态资源，去掉时间戳避免每次列表渲染都绕过浏览器缓存。
	return `${基础地址}static/tp/${图片名称}`
}

function 读取有效字段缓存(缓存键) {
	return 读取有效内存缓存(光伏字段缓存, 缓存键, 静态配置缓存有效时间)
}

function 写入字段缓存(区域类型 = '', 响应数据) {
	const 缓存键 = 标准化区域类型(区域类型)
	const 字段列表 = 解析字段列表(响应数据)

	if (!字段列表.length) {
		return 字段列表
	}

	// 原始响应和字段顺序放在同一条缓存中，一起过期，避免二维数组列错位。
	光伏字段缓存[缓存键] = {
		data: { 响应数据, 字段列表 },
		time: Date.now()
	}

	return 字段列表
}

async function 其他下拉(参数 = {}) {
	const 请求会话 = 确保当前缓存会话()
	const 缓存键 = JSON.stringify(参数)
	const 下拉缓存 = 读取有效内存缓存(光伏下拉响应缓存, 缓存键, 静态配置缓存有效时间)

	if (下拉缓存) {
		return 下拉缓存
	}

	// 下拉内容属于静态配置；缓存响应及请求中的 Promise，避免页面返回或并发初始化时重复请求。
	return 复用在途请求(光伏下拉请求缓存, 缓存键, async () => {
		const 响应数据 = await 新能源请求('其他下拉', 参数)
		const 下拉 = 解析下拉对象(响应数据)
		const 下拉数据 = {
			区域类型: 读取默认区域类型(下拉.区域类型),
			// 设备类型完全取自其他下拉接口，详情页不再依赖本地固定配置。
			设备类型: [...new Set(解析下拉列表(下拉.设备类型))]
		}

		if (请求会话 === 当前缓存会话标识 && 请求会话 === 读取当前缓存会话标识()) {
			光伏下拉响应缓存[缓存键] = {
				data: 下拉数据,
				time: Date.now()
			}
		}
		return 下拉数据
	})
}

async function 读取接口区域类型(参数 = {}) {
	if (参数.区域类型) {
		return 标准化区域类型(参数.区域类型)
	}

	const 下拉 = await 其他下拉()
	return 下拉.区域类型
}

async function gf加载字段(参数 = {}) {
	const 请求会话 = 确保当前缓存会话()
	const 区域类型 = await 读取接口区域类型(参数)
	const 缓存键 = 标准化区域类型(区域类型)
	const 字段缓存 = 读取有效字段缓存(缓存键)

	if (字段缓存) {
		return 字段缓存.响应数据
	}

	return 复用在途请求(光伏字段请求缓存, 缓存键, async () => {
		const 响应数据 = await 新能源请求('gf加载字段', { 区域类型 })
		if (请求会话 === 当前缓存会话标识 && 请求会话 === 读取当前缓存会话标识()) {
			写入字段缓存(区域类型, 响应数据)
		}
		return 响应数据
	})
}

async function 创建光伏数据参数(参数 = {}) {
	const 区域类型 = await 读取接口区域类型(参数)

	return {
		文件: 参数.文件 || 光伏文件名,
		显条: 参数.显条 || 默认显条,
		当页: 参数.当页 || 1,
		模式: 参数.模式 || '查询',
		树选: 参数.树选 || '',
		条件: 参数.条件 || '',
		可见: 参数.可见 !== undefined ? 参数.可见 : 读取可见区域ID(区域类型),
		系统类型: 参数.系统类型 || 光伏系统类型,
		通讯状态: 参数.通讯状态 || '全部状态',
		报警状态: 参数.报警状态 || '全部状态',
		区域类型
	}
}

function 读取参数字段列表(参数 = {}) {
	if (Array.isArray(参数.字段列表) && 参数.字段列表.length) {
		return 解析字段列表(参数.字段列表)
	}

	if (参数.字段响应) {
		return 解析字段列表(参数.字段响应)
	}

	return []
}

function 格式化满发小时数(值) {
	const 文本 = 转为文本(值)

	if (!文本) {
		return '--'
	}

	return /h|小时/i.test(文本) ? 文本 : `${文本} h`
}

function 标准化光伏电站信息(行对象 = {}, 索引 = 0) {
	// gf加载字段已给出固定字段名，映射后直接取值，保留页面原有名称与空值规则。
	const ID = 行对象.ID
	const 原始电站名称 = 转为文本(行对象.电站名称)
	const id = 转为文本(ID) || `${原始电站名称 || '电站'}-${索引}`
	const 电站名称 = 原始电站名称 || '未命名电站'
	const 通讯状态 = 转为文本(行对象.通讯状态)
	const 报警状态 = 转为文本(行对象.报警状态)
	const 日发电量 = 转为文本(行对象.日发电量) || '--'
	const 满发小时数 = 转为文本(行对象.日满发小时)
	const 电站图片 = 转为文本(行对象.图片)

	return {
		...行对象,
		id,
		_key: `${id}-${索引}`,
		ID: ID !== undefined ? ID : id,
		名称: 电站名称,
		电站名称,
		通讯状态,
		离线状态: 通讯状态,
		报警状态,
		报警内容: 转为文本(行对象.报警内容),
		装机容量: 转为文本(行对象.装机容量) || '--',
		发电功率: 转为文本(行对象.发电功率) || '--',
		日发电量,
		当日发电量: 日发电量,
		满发小时数,
		满发小时数文本: 格式化满发小时数(满发小时数),
		当日发电小时数: 满发小时数,
		日辐照量: 转为文本(行对象.日辐照量),
		电站图片,
		图片地址: 创建电站图片地址(电站图片)
	}
}

function 解析光伏电站列表(响应数据, 字段列表 = [], 起始索引 = 0) {
	// gf加载数据的二维数组先按 gf加载字段 的真实字段顺序转成对象，再补齐页面使用的统一展示字段。
	return 解析数据行列表(响应数据, 字段列表, '电站名称')
		.map((行对象, 索引) => 标准化光伏电站信息(行对象, 起始索引 + 索引))
}

function 请求光伏数据(请求参数 = {}) {
	确保当前缓存会话()
	const 缓存键 = JSON.stringify(请求参数)

	// 动态列表不缓存结果，只复用同参数进行中的 Promise，返回后立即释放。
	return 复用在途请求(光伏数据请求缓存, 缓存键, () => 新能源请求('gf加载数据', 请求参数))
}

async function 读取光伏数据字段列表(请求参数 = {}, 字段列表参数 = []) {
	确保当前缓存会话()
	if (字段列表参数.length) {
		return 字段列表参数
	}

	const 区域类型 = 请求参数.区域类型 || 光伏默认区域类型
	const 缓存键 = 标准化区域类型(区域类型)
	const 字段缓存 = 读取有效字段缓存(缓存键)

	if (字段缓存) {
		return 字段缓存.字段列表
	}

	try {
		// 字段来源以 gf加载字段 为准：先拿真实字段顺序，再让 gf加载数据 的二维数组按列映射成对象。
		const 字段响应数据 = await gf加载字段({
			区域类型
		})

		const 最新字段缓存 = 读取有效字段缓存(缓存键)
		return 最新字段缓存 ? 最新字段缓存.字段列表 : 解析字段列表(字段响应数据)
	} catch (错误) {
		return []
	}
}

async function gf加载数据(参数 = {}) {
	确保当前缓存会话()
	const 字段列表参数 = 读取参数字段列表(参数)
	// 参数构造函数只挑选后端需要的字段，无需复制对象后再删除前端辅助字段。
	const 请求参数 = await 创建光伏数据参数(参数)
	// 同一区域字段列表会被缓存；分页加载时只重复请求数据，不重复请求字段定义。
	let 数据字段列表 = await 读取光伏数据字段列表(请求参数, 字段列表参数)
	const 响应数据 = await 请求光伏数据(请求参数)

	if (!数据字段列表.length) {
		数据字段列表 = 解析字段列表(响应数据)
	}

	const 当前页 = Number(请求参数.当页) || 1
	const 每页显条 = Number(请求参数.显条) || 默认显条
	const 起始索引 = (当前页 - 1) * 每页显条

	// gf加载数据返回二维数组时，在接口层按字段顺序完成映射，并统一补齐列表标识与展示空值。
	return 解析光伏电站列表(响应数据, 数据字段列表, 起始索引)
}

// 获取光伏电站详情看板数据
// 参数ID来自电站列表接口返回
async function gf读取(参数 = {}) {
	确保当前缓存会话()
	const 缓存键 = 创建参数缓存键(参数)

	// 详情看板保持实时，只复用完全相同参数的在途 Promise，完成后立即释放。
	return 复用在途请求(光伏详情请求缓存, 缓存键, () => {
		return 新能源请求('gf读取', 参数)
			.then((响应数据) => 响应数据 && typeof 响应数据 === 'object' ? 响应数据.form : undefined)
			.catch(() => ({}))
	})
}

