const 光伏详情请求缓存 = Object.create(null)
let 当前缓存会话标识 = null

function 清空缓存对象(缓存对象) {
	Object.keys(缓存对象).forEach((缓存键) => {
		delete 缓存对象[缓存键]
	})
}

function 确保当前缓存会话() {
	const 当前会话 = 读取当前缓存会话标识()

	if (当前缓存会话标识 === 当前会话) {
		return 当前会话
	}

	// 登录会话变化后清空本模块引用，避免新账号命中旧账号的静态结果或在途请求。
	[
		光伏字段响应缓存,
		光伏字段列表缓存,
		光伏字段请求缓存,
		光伏下拉响应缓存,
		光伏下拉请求缓存,
		光伏数据请求缓存,
		光伏详情请求缓存
	].forEach(清空缓存对象)
	当前缓存会话标识 = 当前会话

	return 当前会话
}

