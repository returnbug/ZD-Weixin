function 格式化满发小时数(值) {
	const 文本 = 转为文本(值)

	if (!文本) {
		return '--'
	}

	return /h|小时/i.test(文本) ? 文本 : `${文本} h`
}

function 标准化光伏电站信息(行对象 = {}, 索引 = 0) {
	const ID = 读取光伏字段原值(行对象, 'ID')
	const 原始电站名称 = 读取光伏字段文本(行对象, '电站名称')
	const id = 转为文本(ID) || `${原始电站名称 || '电站'}-${索引}`
	const 电站名称 = 原始电站名称 || '未命名电站'
	const 通讯状态 = 读取光伏字段文本(行对象, '通讯状态')
	const 报警状态 = 读取光伏字段文本(行对象, '报警状态')
	const 日发电量 = 读取光伏字段文本(行对象, '日发电量') || '--'
	const 满发小时数 = 读取光伏字段文本(行对象, '日满发小时')
	const 电站图片 = 读取光伏字段文本(行对象, '图片')

	return {
		...行对象,
		id,
		_key: `${id}-${索引}`,
		ID: ID !== undefined ? ID : id,
		名称: 电站名称,
		电站名称,
		通讯状态,
		离线状态: 通讯状态,
		报警状态,
		报警内容: 读取光伏字段文本(行对象, '报警内容'),
		装机容量: 读取光伏字段文本(行对象, '装机容量') || '--',
		发电功率: 读取光伏字段文本(行对象, '发电功率') || '--',
		日发电量,
		当日发电量: 日发电量,
		满发小时数,
		满发小时数文本: 格式化满发小时数(满发小时数),
		当日发电小时数: 满发小时数,
		日辐照量: 读取光伏字段文本(行对象, '日辐照量'),
		电站图片,
		图片地址: 创建电站图片地址(电站图片)
	}
}

function 解析光伏电站列表(响应数据, 字段列表 = [], 起始索引 = 0) {
	// gf加载数据的二维数组先按 gf加载字段 的真实字段顺序转成对象，再补齐页面使用的统一展示字段。
	return 解析光伏行列表(响应数据, 字段列表).map((行对象, 索引) => 标准化光伏电站信息(行对象, 起始索引 + 索引))
}

function 请求光伏数据(请求参数 = {}) {
	确保当前缓存会话()
	const 缓存键 = JSON.stringify(请求参数)

	if (光伏数据请求缓存[缓存键]) {
		return 光伏数据请求缓存[缓存键]
	}

	// 动态列表不缓存结果，只复用同参数进行中的 Promise，返回后立即释放。
	const 数据请求 = 新能源请求('gf加载数据', 请求参数).finally(() => {
		if (光伏数据请求缓存[缓存键] === 数据请求) {
			delete 光伏数据请求缓存[缓存键]
		}
	})

	光伏数据请求缓存[缓存键] = 数据请求

	return 数据请求
}

async function 读取光伏数据字段列表(请求参数 = {}, 字段列表参数 = []) {
	确保当前缓存会话()
	if (字段列表参数.length) {
		return 字段列表参数
	}

	const 区域类型 = 请求参数.区域类型 || 光伏默认区域类型
	const 缓存键 = 读取字段缓存键(区域类型)
	const 字段缓存 = 读取有效字段缓存(缓存键)

	if (字段缓存) {
		return 字段缓存.字段列表
	}

	try {
		// 字段来源以 gf加载字段 为准：先拿真实字段顺序，再让 gf加载数据 的二维数组按列映射成对象。
		const 字段响应数据 = await gf加载字段({
			区域类型
		})

		const 最新字段缓存 = 读取有效字段缓存(缓存键)
		return 最新字段缓存 ? 最新字段缓存.字段列表 : 解析字段列表(字段响应数据)
	} catch (错误) {
		return []
	}
}

async function gf加载数据(参数 = {}) {
	确保当前缓存会话()
	const 字段列表参数 = 读取参数字段列表(参数)
	const 请求参数源 = {
		...参数
	}

	delete 请求参数源.字段列表
	delete 请求参数源.字段响应

	const 请求参数 = await 创建光伏数据参数(请求参数源)
	// 同一区域字段列表会被缓存；分页加载时只重复请求数据，不重复请求字段定义。
	let 数据字段列表 = await 读取光伏数据字段列表(请求参数, 字段列表参数)
	const 响应数据 = await 请求光伏数据(请求参数)

	if (!数据字段列表.length) {
		数据字段列表 = 解析字段列表(响应数据)
	}

	const 当前页 = Number(请求参数.当页) || 1
	const 每页显条 = Number(请求参数.显条) || 默认显条
	const 起始索引 = (当前页 - 1) * 每页显条

	// gf加载数据返回二维数组时，在接口层按字段顺序完成映射，并统一补齐列表标识与展示空值。
	return 解析光伏电站列表(响应数据, 数据字段列表, 起始索引)
}

// 获取光伏电站详情看板数据
// 参数ID来自电站列表接口返回
async function gf读取(参数 = {}) {
	确保当前缓存会话()
	const 缓存键 = JSON.stringify(Object.keys(参数).sort().reduce((结果, 键) => {
		结果[键] = 参数[键]
		return 结果
	}, {}))

	if (光伏详情请求缓存[缓存键]) {
		return 光伏详情请求缓存[缓存键]
	}

	// 详情看板保持实时，只复用完全相同参数的在途 Promise，完成后立即释放。
	const 详情请求 = 新能源请求('gf读取', 参数).then((响应数据) => {
		return 响应数据 && typeof 响应数据 === 'object' ? 响应数据.form : undefined
	}).catch(() => ({})).finally(() => {
		if (光伏详情请求缓存[缓存键] === 详情请求) {
			delete 光伏详情请求缓存[缓存键]
		}
	})

	光伏详情请求缓存[缓存键] = 详情请求

	return 详情请求
}

