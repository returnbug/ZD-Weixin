function 创建电站图片地址(电站图片 = '') {
	const 图片名称 = 转为文本(电站图片).replace(/^\/+/, '')

	if (!图片名称) {
		return ''
	}

	const 基础地址 = 新能源基础地址.endsWith('/') ? 新能源基础地址 : `${新能源基础地址}/`

	// 电站图片是后端静态资源，去掉时间戳避免每次列表渲染都绕过浏览器缓存。
	return `${基础地址}static/tp/${图片名称}`
}

function 读取字段缓存键(区域类型 = '') {
	return 标准化区域类型(区域类型)
}

function 读取有效字段缓存(缓存键) {
	const 响应缓存 = 光伏字段响应缓存[缓存键]
	const 列表缓存 = 光伏字段列表缓存[缓存键]
	const 当前时间 = Date.now()
	const 缓存有效 = 响应缓存 && 列表缓存 &&
		当前时间 - 响应缓存.time <= 静态配置缓存有效时间 &&
		当前时间 - 列表缓存.time <= 静态配置缓存有效时间

	if (缓存有效) {
		return {
			响应数据: 响应缓存.data,
			字段列表: 列表缓存.data
		}
	}

	// 原始响应与解析后的字段顺序必须成对失效，避免二维数据按过期列顺序映射。
	delete 光伏字段响应缓存[缓存键]
	delete 光伏字段列表缓存[缓存键]
	return null
}

function 写入字段缓存(区域类型 = '', 响应数据) {
	const 缓存键 = 读取字段缓存键(区域类型)
	const 字段列表 = 解析字段列表(响应数据)

	if (!字段列表.length) {
		return 字段列表
	}

	// 字段来源固定为 gf加载字段；同一区域类型字段顺序稳定，缓存后可避免页面反复进入时重复请求。
	const 缓存时间 = Date.now()
	光伏字段响应缓存[缓存键] = {
		data: 响应数据,
		time: 缓存时间
	}
	光伏字段列表缓存[缓存键] = {
		data: 字段列表,
		time: 缓存时间
	}

	return 字段列表
}

function 解析设备类型列表(设备类型数据) {
	return [...new Set(读取数组(设备类型数据).map((设备类型) => {
		if (设备类型 && typeof 设备类型 === 'object' && !Array.isArray(设备类型)) {
			return 转为文本(读取对象字段(设备类型, ['名称', 'name', 'label', '值', 'value', 'ID', 'id']))
		}

		return 转为文本(设备类型)
	}).filter(Boolean))]
}

async function 其他下拉(参数 = {}) {
	const 请求会话 = 确保当前缓存会话()
	const 缓存键 = JSON.stringify(参数)
	const 下拉缓存 = 光伏下拉响应缓存[缓存键]

	if (下拉缓存 && Date.now() - 下拉缓存.time <= 静态配置缓存有效时间) {
		return 下拉缓存.data
	}

	if (下拉缓存) {
		delete 光伏下拉响应缓存[缓存键]
	}

	if (光伏下拉请求缓存[缓存键]) {
		return 光伏下拉请求缓存[缓存键]
	}

	// 下拉内容属于静态配置；缓存响应及请求中的 Promise，避免页面返回或并发初始化时重复请求。
	const 下拉请求 = 新能源请求('其他下拉', 参数).then((响应数据) => {
		const 下拉 = 解析下拉对象(响应数据)
		const 下拉数据 = {
			区域类型: 读取默认区域类型(下拉.区域类型),
			// 设备类型完全取自其他下拉接口，详情页不再依赖本地固定配置。
			设备类型: 解析设备类型列表(下拉.设备类型)
		}

		if (请求会话 === 当前缓存会话标识 && 请求会话 === 读取当前缓存会话标识()) {
			光伏下拉响应缓存[缓存键] = {
				data: 下拉数据,
				time: Date.now()
			}
		}
		return 下拉数据
	}).finally(() => {
		if (光伏下拉请求缓存[缓存键] === 下拉请求) {
			delete 光伏下拉请求缓存[缓存键]
		}
	})

	光伏下拉请求缓存[缓存键] = 下拉请求

	return 下拉请求
}

async function 读取接口区域类型(参数 = {}) {
	if (参数.区域类型) {
		return 标准化区域类型(参数.区域类型)
	}

	const 下拉 = await 其他下拉()
	return 下拉.区域类型
}

async function gf加载字段(参数 = {}) {
	const 请求会话 = 确保当前缓存会话()
	const 区域类型 = await 读取接口区域类型(参数)
	const 缓存键 = 读取字段缓存键(区域类型)
	const 字段缓存 = 读取有效字段缓存(缓存键)

	if (字段缓存) {
		return 字段缓存.响应数据
	}

	if (光伏字段请求缓存[缓存键]) {
		return 光伏字段请求缓存[缓存键]
	}

	const 字段请求 = 新能源请求('gf加载字段', {
		区域类型
	}).then((响应数据) => {
		if (请求会话 === 当前缓存会话标识 && 请求会话 === 读取当前缓存会话标识()) {
			写入字段缓存(区域类型, 响应数据)
		}
		return 响应数据
	}).finally(() => {
		if (光伏字段请求缓存[缓存键] === 字段请求) {
			delete 光伏字段请求缓存[缓存键]
		}
	})

	光伏字段请求缓存[缓存键] = 字段请求

	return 字段请求
}

async function 创建光伏数据参数(参数 = {}) {
	const 区域类型 = await 读取接口区域类型(参数)

	return {
		文件: 参数.文件 || 光伏文件名,
		显条: 参数.显条 || 默认显条,
		当页: 参数.当页 || 1,
		模式: 参数.模式 || '查询',
		树选: 参数.树选 || '',
		条件: 参数.条件 || '',
		可见: 参数.可见 !== undefined ? 参数.可见 : 读取可见区域ID(区域类型),
		系统类型: 参数.系统类型 || 光伏系统类型,
		通讯状态: 参数.通讯状态 || '全部状态',
		报警状态: 参数.报警状态 || '全部状态',
		区域类型
	}
}

