const 默认区域类型 = '区域1'
const 设备列表文件名 = '设备列表'
const 默认设备模版 = '全部模版'
const 默认显条 = 100
const 静态配置缓存有效时间 = 30 * 60 * 1000
const 设备字段响应缓存 = Object.create(null)
const 设备字段列表缓存 = Object.create(null)
const 设备字段请求缓存 = Object.create(null)
const 设备数据请求缓存 = Object.create(null)
const 设备详情请求缓存 = Object.create(null)
const 设备日志请求缓存 = Object.create(null)
let 当前缓存会话标识 = null

function 清空缓存对象(缓存对象) {
	Object.keys(缓存对象).forEach((缓存键) => {
		delete 缓存对象[缓存键]
	})
}

function 确保当前缓存会话() {
	const 当前会话 = 读取当前缓存会话标识()

	if (当前缓存会话标识 === 当前会话) {
		return 当前会话
	}

	// 登录会话变化时清空设备字段和在途请求引用，避免不同账号复用权限范围内的数据。
	[
		设备字段响应缓存,
		设备字段列表缓存,
		设备字段请求缓存,
		设备数据请求缓存,
		设备详情请求缓存,
		设备日志请求缓存
	].forEach(清空缓存对象)
	当前缓存会话标识 = 当前会话

	return 当前会话
}

function 创建参数缓存键(参数 = {}) {
	return JSON.stringify(Object.keys(参数).sort().reduce((结果, 键) => {
		结果[键] = 参数[键]
		return 结果
	}, {}))
}

function 读取有效字段缓存(缓存键) {
	const 响应缓存 = 设备字段响应缓存[缓存键]
	const 列表缓存 = 设备字段列表缓存[缓存键]
	const 当前时间 = Date.now()
	const 缓存有效 = 响应缓存 && 列表缓存 &&
		当前时间 - 响应缓存.time <= 静态配置缓存有效时间 &&
		当前时间 - 列表缓存.time <= 静态配置缓存有效时间

	if (缓存有效) {
		return {
			响应数据: 响应缓存.data,
			字段列表: 列表缓存.data
		}
	}

	delete 设备字段响应缓存[缓存键]
	delete 设备字段列表缓存[缓存键]
	return null
}

function 创建设备字段参数(参数 = {}) {
	return {
		区域类型: 标准化区域类型(参数.区域类型, 默认区域类型),
		设备类型: 转为文本(参数.设备类型)
	}
}

function 读取设备API地址(设备类型 = '') {
	return 转为文本(设备类型) === '逆变器' ? 'nbq' : 'db'
}

async function 请求设备字段(API地址 = 'nbq', 参数 = {}) {
	const 请求会话 = 确保当前缓存会话()
	const 请求参数 = 创建设备字段参数(参数)
	const 缓存键 = `${API地址}:${创建参数缓存键(请求参数)}`
	const 字段缓存 = 读取有效字段缓存(缓存键)

	if (字段缓存) {
		return 字段缓存.响应数据
	}

	if (设备字段请求缓存[缓存键]) {
		return 设备字段请求缓存[缓存键]
	}

	// 字段接口决定当前设备类型的展示列，原始响应和解析顺序需要成对缓存。
	const 字段请求 = 新能源请求(`${API地址}加载字段`, 请求参数).then((响应数据) => {
		if (请求会话 === 当前缓存会话标识 && 请求会话 === 读取当前缓存会话标识()) {
			const 缓存时间 = Date.now()
			设备字段响应缓存[缓存键] = {
				data: 响应数据,
				time: 缓存时间
			}
			设备字段列表缓存[缓存键] = {
				data: 解析字段列表(响应数据),
				time: 缓存时间
			}
		}

		return 响应数据
	}).finally(() => {
		if (设备字段请求缓存[缓存键] === 字段请求) {
			delete 设备字段请求缓存[缓存键]
		}
	})

	设备字段请求缓存[缓存键] = 字段请求
	return 字段请求
}

async function nbq加载字段(参数 = {}) {
	return 请求设备字段('nbq', 参数)
}

async function db加载字段(参数 = {}) {
	return 请求设备字段('db', 参数)
}

function 创建设备数据参数(参数 = {}) {
	const 区域类型 = 标准化区域类型(参数.区域类型, 默认区域类型)
	const 设备类型 = 转为文本(参数.设备类型)

	// 参数名、顺序和默认值与网页端设备列表的查询 FormData 保持一致。
	return {
		文件: 转为文本(参数.文件) || 设备列表文件名,
		显条: 参数.显条 || 默认显条,
		当页: 参数.当页 || 1,
		模式: 参数.模式 || '查询',
		树选: 参数.树选 || '',
		条件: 参数.条件 || '',
		可见: 参数.可见 !== undefined ? 参数.可见 : 读取可见区域ID(区域类型),
		系统类型: 参数.系统类型 || '全部类型',
		设备类型,
		设备模版: 参数.设备模版 || 默认设备模版,
		通讯状态: 参数.通讯状态 || '全部状态',
		报警状态: 参数.报警状态 || '全部状态',
		区域类型
	}
}

function 请求设备数据(API地址 = 'nbq', 请求参数 = {}) {
	确保当前缓存会话()
	const 缓存键 = `${API地址}:${创建参数缓存键(请求参数)}`

	if (设备数据请求缓存[缓存键]) {
		return 设备数据请求缓存[缓存键]
	}

	// 列表数据保持实时，只复用相同参数的在途 Promise，请求结束后立即释放。
	const 数据请求 = 新能源请求(`${API地址}加载数据`, 请求参数).finally(() => {
		if (设备数据请求缓存[缓存键] === 数据请求) {
			delete 设备数据请求缓存[缓存键]
		}
	})

	设备数据请求缓存[缓存键] = 数据请求
	return 数据请求
}

async function nbq加载数据(参数 = {}) {
	return 请求设备数据('nbq', 创建设备数据参数(参数))
}

